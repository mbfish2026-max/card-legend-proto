// 装备对比改版：左右并排数据行（对齐、差值符号、空部位、双槽位、越低越好）
import { compareRows, compareSlot, cmpScore, diffText, UP, DOWN, SAME } from '../src/ui/equipCompare';
let n = 0; const ok = (c: boolean, m: string) => { if (!c) { throw new Error('FAIL ' + m); } n++; console.log('ok', m); };
const mk = (uid: number, slot: any, stats: any, name = 'x' + uid, req = 1): any => ({ uid, item: 'x', name, rarity: 'common', slot, stats, req, price: 1 });
const w1 = mk(1, 'weapon', { atk: 10, mag: 2 }, '木剑', 1), w2 = mk(2, 'weapon', { atk: 15, hp: 5 }, '好剑', 4);
let D = compareRows(w2, { weapon: w1 })!;
ok(D.left === w1 && D.slot === 'weapon', '左侧是身上同部位');
ok(D.rows.map(r => r.key).join() === 'atk,mag,hp,req', `属性并集按固定顺序对齐（${D.rows.map(r => r.key)}）`);
const R = (k: string) => D.rows.find(r => r.key === k)!;
ok(R('atk').diff === 5 && R('atk').color === UP && diffText(R('atk')) === '+5', '更高 → 绿 +5');
ok(R('mag').right === '0' && R('mag').diff === -2 && R('mag').color === DOWN, '右侧缺项显示 0、更低 → 红');
ok(R('hp').left === '0' && R('hp').color === UP, '左侧缺项显示 0');
ok(R('req').diff === 3 && R('req').color === DOWN, '需要等级越低越好：更高 → 红（反向）');
ok(compareRows(mk(9, 'weapon', { atk: 10, mag: 2 }), { weapon: w1 })!.rows.every(r => r.color === SAME && (r.key === 'req' || diffText(r) === '=')), '相同 → 灰 =');
D = compareRows(w2, {})!;
ok(D.left === null && D.rows.every(r => r.left === '—' && r.color === UP), '空部位：左「—」右全绿');
ok(compareRows(w1, { weapon: w1 }) === null, '已穿戴自身不对比');
ok(compareRows(mk(7, undefined, {}), { weapon: w1 }) === null, '杂物不对比');
const ra = mk(3, 'ring', { atk: 1 }), rb = mk(4, 'ring', { atk: 5 }), nr = mk(5, 'ring', { atk: 3 });
ok(compareSlot(nr, { ring1: ra }) === 'ring2', '双槽位有空位取空位');
D = compareRows(nr, { ring1: rb, ring2: ra })!;
ok(D.left === ra && D.other === rb && D.rows.find(r => r.key === 'atk')!.diff === 2, '双槽位都穿：左侧取较弱一件，另一件列为 other');
ok(compareRows(mk(6, 'bracelet', { def: 1 }), { bracelet1: mk(8, 'bracelet', { def: 2, hp: 30 }), bracelet2: mk(10, 'bracelet', { def: 4 }) })!.left!.uid === 10, '手镯评分（生命 0.1 分）');
ok(cmpScore(mk(11, 'weapon', { atk: 2, hp: 10 })) === 3, '评分函数');
console.log(`装备对比测试全部通过 ${n} 项`);
