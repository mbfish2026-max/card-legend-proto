import { sortBag, BAG_STACK_MAX } from '../src/combat/bagSort';
import { World } from '../src/combat/World';
import { FLOORS } from '../src/data/world';
import { WORLD } from '../src/data/world';
let n = 0; const ok = (c: boolean, m: string) => { if (!c) throw new Error('FAIL ' + m); n++; };
let u = 1; const eq = (rarity: any, req: number, slot: any = 'weapon'): any => ({ uid: u++, item: 'e' + req, name: 'e', rarity, slot, stats: {}, req, price: 1 });
const ore = (qty: number, purity = 1): any => ({ uid: u++, item: 'black_iron', name: '黑铁', rarity: 'common', stats: {}, req: 1, price: 1, qty, purity });
const a = [eq('common', 5), eq('rare', 3), eq('magic', 9), eq('rare', 10), ore(2), ore(3), ore(1, 2)];
const s = sortBag(a);
ok(s.map(x => x.rarity + x.req).slice(0, 4).join() === 'rare10,rare3,magic9,common5', '品质→等级降序');
ok(s.filter(x => x.item === 'black_iron' && x.purity === 1).length === 1 && s.find(x => x.purity === 1 && x.item === 'black_iron')!.qty === 5, '同纯度合并');
ok(s.filter(x => x.item === 'black_iron').length === 2, '不同纯度不合并');
ok(a[4].qty === 2, '不修改入参');
ok(sortBag([]).length === 0, '空背包');
const big = sortBag([ore(BAG_STACK_MAX - 1), ore(5)]); ok(big.length === 2 && big[0].qty! + big[1].qty! === BAG_STACK_MAX + 4 && big.every(x => x.qty! <= BAG_STACK_MAX), '堆叠上限拆堆');
ok(sortBag([ore(BAG_STACK_MAX + 10)]).every(x => x.qty! <= BAG_STACK_MAX), '超上限旧堆拆分');
const full = Array.from({ length: WORLD.bagSize }, (_, i) => eq(['common', 'magic', 'rare'][i % 3] as any, i % 40));
const fs = sortBag(full); ok(fs.length === WORLD.bagSize && new Set(fs.map(x => x.uid)).size === WORLD.bagSize, '满背包（200 格）整理不丢不重');
for (let i = 1; i < fs.length; i++) ok(!(fs[i].rarity === fs[i - 1].rarity && fs[i].req > fs[i - 1].req), '满包顺序');
const w = new World(() => 0.5, 30, FLOORS, 'warrior'); const worn = eq('common', 1); w.equip.weapon = worn; w.bag = [eq('common', 1), eq('rare', 2), ore(1), ore(1)];
w.sortBag(); ok(w.equip.weapon === worn && w.bag.length === 3 && w.bag[0].rarity === 'rare', 'World.sortBag：已穿不动、合并');
console.log(`背包整理测试全部通过 ${n} 项`);
